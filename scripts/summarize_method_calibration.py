#!/usr/bin/env python3
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    rows = []
    pattern = "controlled-method-calibration-*-v2-*/manifest.json"
    for manifest_path in sorted((ROOT / "results" / "runs").glob(pattern)):
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        metrics = json.loads((manifest_path.parent / "metrics.json").read_text(encoding="utf-8"))
        rows.append((manifest, metrics))
    if len(rows) != 18:
        raise SystemExit(f"Expected 18 method-calibration cells, found {len(rows)}")

    lines = [
        "# Final exploratory method calibration",
        "",
        "**EXPLORATORY ONLY. These values use the contaminated v1 development test and are not "
        "confirmatory evidence.**",
        "",
        "Generated by `python scripts/summarize_method_calibration.py` from committed raw "
        "artifacts.",
        "",
        "| Model | Method | Forget oracle KL | Forget NLL | Retain NLL | Utility NLL | "
        "Optimize s | "
        "Peak GiB | Parameter L2 from trained |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for manifest, metrics in rows:
        distance = manifest["method_metadata"].get("parameter_l2_distance_from_full", 0.0)
        lines.append(
            f"| {manifest['model_name']} | {manifest['method']} | "
            f"{metrics['forget_oracle_kl']:.4f} | {metrics['forget_nll']:.4f} | "
            f"{metrics['retain_nll']:.4f} | {metrics['utility_nll']:.4f} | "
            f"{manifest['optimization_runtime_seconds']:.3f} | "
            f"{manifest['peak_vram_bytes'] / 2**30:.2f} | {distance:.6f} |"
        )
    lines.extend(
        [
            "",
            "All methods completed with finite parameters. The calibration was used to verify "
            "stability and cost, not to select a best observed method. The confirmatory protocol "
            "retains all nine prespecified methods and all three seeds.",
            "",
        ]
    )
    destination = ROOT / "reports" / "method_calibration.md"
    destination.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {destination}")


if __name__ == "__main__":
    main()
